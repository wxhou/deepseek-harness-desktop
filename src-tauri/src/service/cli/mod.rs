/// Windows `dsh.cmd` 内容。`app_dir` 为应用数据目录（绝对路径，生成时写死）。
// 生产环境仅在 Windows 使用；Unix 构建下仍编译（供跨平台测试引用）。
#[cfg_attr(all(not(windows), not(test)), allow(dead_code))]
fn build_cmd_shim(app_dir: &Path) -> String {
    let dsh_bin = app_dir
        .join("dependencies/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js");
    let dsh_home = app_dir.join("data/dsh");
    // 批处理中 `%` 会被展开，需写成 `%%`
    let esc = |s: &Path| s.to_string_lossy().replace('%', "%%");
    format!(
        r#"@echo off
rem DeepSeek Harness Desktop - dsh command shim (generated)
rem Do not edit: regenerated by the desktop app on install/startup.
setlocal
set "DSH_APP_DIR={app_dir}"
set "DSH_BIN={dsh_bin}"
set "DSH_HOME={dsh_home}"
set "DSH_TELEMETRY_DISABLED=1"

rem Prefer a version-compatible local node, fall back to the bundled runtime.
where node >nul 2>nul
if errorlevel 1 goto :use_bundled
for /f "delims=" %%v in ('node --version 2^>nul') do set "NODE_V=%%v"
powershell -NoProfile -ExecutionPolicy Bypass -Command "& {{ param($v) if ($v -match '^v(\d+)\.(\d+)') {{ $m=[int]$matches[1]; $n=[int]$matches[2]; if (($m -eq 22 -and $n -ge 15) -or ($m -eq 23 -and $n -ge 8) -or $m -ge 24) {{ exit 0 }} }}; exit 1 }}" "%NODE_V%" >nul 2>nul
if errorlevel 1 goto :use_bundled
set "NODE=node"
goto :launch

:use_bundled
if not exist "%DSH_APP_DIR%\runtime\node.exe" goto :no_node
set "NODE=%DSH_APP_DIR%\runtime\node.exe"
set "PATH=%DSH_APP_DIR%\runtime;%PATH%"

:launch
if not exist "%DSH_BIN%" goto :no_cli
"%NODE%" "%DSH_BIN%" %*
exit /b %ERRORLEVEL%

:no_cli
echo [dsh] Harness CLI not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1

:no_node
echo [dsh] Node.js runtime not found. Please run DeepSeek Harness Desktop to install it first. 1>&2
exit /b 1
"#,
        app_dir = esc(app_dir),
        dsh_bin = esc(&dsh_bin),
        dsh_home = esc(&dsh_home),
    )
}

/// Windows `dsh.ps1` 内容
#[cfg_attr(all(not(windows), not(test)), allow(dead_code))]
fn build_ps1_shim(app_dir: &Path) -> String {
    let dsh_bin = app_dir.join("dependencies/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js");
    let dsh_home = app_dir.join("data/dsh");
    // 单引号字符串中 `'` 需翻倍
    let esc = |s: &Path| s.to_string_lossy().replace('\'', "''");
    format!(
        r#"# DeepSeek Harness Desktop - dsh command shim (generated)
# Do not edit: regenerated by the desktop app on install/startup.
$ErrorActionPreference = "Stop"
$appDir = '{app_dir}'
$dshBin = '{dsh_bin}'
$env:DSH_HOME = '{dsh_home}'
$env:DSH_TELEMETRY_DISABLED = '1'

# Prefer a version-compatible local node, fall back to the bundled runtime.
$node = $null
$localNode = Get-Command node -ErrorAction SilentlyContinue
if ($localNode) {{
    try {{
        $version = & node --version 2>$null
        if ($version -match '^v(\d+)\.(\d+)') {{
            $major = [int]$matches[1]
            $minor = [int]$matches[2]
            if (($major -eq 22 -and $minor -ge 15) -or ($major -eq 23 -and $minor -ge 8) -or $major -ge 24) {{
                $node = 'node'
            }}
        }}
    }} catch {{ }}
}}
if (-not $node) {{
    $bundled = Join-Path $appDir 'runtime\node.exe'
    if (Test-Path -LiteralPath $bundled) {{
        $node = $bundled
        $env:PATH = (Split-Path -Parent $bundled) + ';' + $env:PATH
    }}
}}
if (-not $node) {{
    Write-Error '[dsh] Node.js runtime not found. Please run DeepSeek Harness Desktop to install it first.'
    exit 1
}}
if (-not (Test-Path -LiteralPath $dshBin)) {{
    Write-Error '[dsh] Harness CLI not found. Please run DeepSeek Harness Desktop to install it first.'
    exit 1
}}
& $node $dshBin @args
exit $LASTEXITCODE
"#,
        app_dir = esc(app_dir),
        dsh_bin = esc(&dsh_bin),
        dsh_home = esc(&dsh_home),
    )
}

/// Unix `dsh` shell 脚本内容（POSIX sh）
#[cfg_attr(all(windows, not(test)), allow(dead_code))]
fn build_sh_shim(app_dir: &Path) -> String {
    let dsh_bin = app_dir.join("dependencies/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js");
    let dsh_home = app_dir.join("data/dsh");
    // 单引号字符串中 `'` 需写成 `'\''`
    let esc = |s: &Path| s.to_string_lossy().replace('\'', "'\\''");
    format!(
        r#"#!/bin/sh
# DeepSeek Harness Desktop - dsh command shim (generated)
# Do not edit: regenerated by the desktop app on install/startup.
APP_DIR='{app_dir}'
DSH_BIN='{dsh_bin}'
export DSH_HOME='{dsh_home}'
export DSH_TELEMETRY_DISABLED=1

# Prefer a version-compatible local node, fall back to the bundled runtime.
NODE=""
if command -v node >/dev/null 2>&1; then
  NODE_V=$(node --version 2>/dev/null)
  MAJOR=$(printf '%s' "$NODE_V" | awk -F. '{{ gsub(/^v/, "", $1); print $1 }}')
  MINOR=$(printf '%s' "$NODE_V" | awk -F. '{{ print $2 }}')
  if {{ [ -n "$MAJOR" ] && [ "$MAJOR" -ge 24 ]; }} 2>/dev/null || \
     {{ [ "$MAJOR" -eq 22 ] && [ "$MINOR" -ge 15 ]; }} 2>/dev/null || \
     {{ [ "$MAJOR" -eq 23 ] && [ "$MINOR" -ge 8 ]; }} 2>/dev/null; then
    NODE="node"
  fi
fi
if [ -z "$NODE" ]; then
  if [ -x "$APP_DIR/runtime/bin/node" ]; then
    NODE="$APP_DIR/runtime/bin/node"
    export PATH="$APP_DIR/runtime/bin:$PATH"
  fi
fi
if [ -z "$NODE" ]; then
  echo "[dsh] Node.js runtime not found. Please run DeepSeek Harness Desktop to install it first." >&2
  exit 1
fi
if [ ! -f "$DSH_BIN" ]; then
  echo "[dsh] Harness CLI not found. Please run DeepSeek Harness Desktop to install it first." >&2
  exit 1
fi
exec "$NODE" "$DSH_BIN" "$@"
"#,
        app_dir = esc(app_dir),
        dsh_bin = esc(&dsh_bin),
        dsh_home = esc(&dsh_home),
    )
}

/// 将 shim 文件写入 bin 目录（覆盖式，保证自愈后内容与当前安装一致）
fn write_shims(app_handle: &AppHandle, bin_dir: &Path) -> Result<(), String> {
    let app_dir = config::get_base_dir(app_handle);
    fs::create_dir_all(bin_dir).map_err(|e| format!("create bin dir failed: {e}"))?;

    #[cfg(windows)]
    {
        fs::write(bin_dir.join(SHIM_CMD_NAME), build_cmd_shim(&app_dir))
            .map_err(|e| format!("write {} failed: {e}", SHIM_CMD_NAME))?;
        fs::write(bin_dir.join(SHIM_PS1_NAME), build_ps1_shim(&app_dir))
            .map_err(|e| format!("write {} failed: {e}", SHIM_PS1_NAME))?;
    }
    #[cfg(not(windows))]
    {
        let shim = bin_dir.join(SHIM_SH_NAME);
        fs::write(&shim, build_sh_shim(&app_dir))
            .map_err(|e| format!("write {} failed: {e}", SHIM_SH_NAME))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&shim, fs::Permissions::from_mode(0o755))
                .map_err(|e| format!("chmod shim failed: {e}"))?;
        }
    }
    Ok(())
}

