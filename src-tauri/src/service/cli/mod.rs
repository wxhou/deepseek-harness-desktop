//! 命令行集成：安装后在用户 PATH 中注册 `dsh` 命令。
//!
//! `dsh` 是 Node 脚本（`@deepseek-ai/dsh/lib/bin.js`），并非原生可执行文件，
//! 因此这里生成包装脚本（shim）并注册到用户 PATH：
//!
//! - Windows：`%LOCALAPPDATA%\deepseek-harness\bin\dsh.cmd` + `dsh.ps1`，
//!   通过 `HKCU\Environment\Path` 注册并广播 `WM_SETTINGCHANGE`；
//! - macOS/Linux：`~/.local/bin/dsh`，必要时向 `~/.zshrc` / `~/.bashrc`
//!   幂等追加 PATH 导出（带标记块，可干净移除）。
//!
//! shim 运行时优先使用本地版本兼容的 node（校验规则与
//! [`crate::config::is_supported_node_version`] 一致），否则回退到捆绑运行时。
//! shim 不重定向 stdin/stdout、不修改工作目录，保证交互式 `dsh` 可用，
//! 并透传全部参数与退出码。

use crate::config;
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use tauri::{AppHandle, Manager};

/// Windows 下 shim 根目录名（`%LOCALAPPDATA%\<此目录>\bin`）
const CLI_ROOT_DIR_NAME: &str = "deepseek-harness";
/// Windows 下 shim 文件名（cmd 为主入口，ps1 供 PowerShell 原生体验）
const SHIM_CMD_NAME: &str = "dsh.cmd";
const SHIM_PS1_NAME: &str = "dsh.ps1";
/// Unix 下 shim 文件名
#[cfg_attr(windows, allow(dead_code))]
const SHIM_SH_NAME: &str = "dsh";
/// Unix 下 shim 所在目录（XDG 约定）
#[cfg_attr(windows, allow(dead_code))]
const UNIX_BIN_DIR: &str = ".local/bin";

/// shell rc 注入标记（用于幂等增删）
#[cfg_attr(windows, allow(dead_code))]
const RC_MARK_START: &str = "# >>> deepseek-harness dsh >>>";
#[cfg_attr(windows, allow(dead_code))]
const RC_MARK_END: &str = "# <<< deepseek-harness dsh <<<";

/// Unix 下需要写入 PATH 导出的 rc 文件（按顺序处理）
#[cfg_attr(windows, allow(dead_code))]
const RC_FILES: [&str; 2] = [".zshrc", ".bashrc"];

/// 命令行集成状态（设置页展示）
#[derive(Debug, Clone, Serialize)]
pub struct CliLinkStatus {
    /// 用户开关（Setting.cli_link_enabled）
    pub enabled: bool,
    /// 主 shim 文件是否存在
    pub shim_exists: bool,
    /// bin 目录是否已在用户 PATH 中注册
    pub path_registered: bool,
    /// bin 目录绝对路径
    pub bin_dir: String,
    /// 主 shim 文件绝对路径
    pub shim_path: String,
}

// ---------------------------------------------------------------------------
// 路径计算
// ---------------------------------------------------------------------------

/// bin 目录：
/// - Windows：`%LOCALAPPDATA%\deepseek-harness\bin`（用户级、不随应用数据目录变动）
/// - Unix：`~/.local/bin`（XDG 约定，通常已在 PATH 中）
fn get_bin_dir(app_handle: &AppHandle) -> PathBuf {
    #[cfg(windows)]
    {
        let local = std::env::var_os("LOCALAPPDATA")
            .map(PathBuf::from)
            .or_else(|| {
                app_handle
                    .path()
                    .local_data_dir()
                    .ok()
                    .and_then(|d| d.parent().map(|p| p.to_path_buf()))
            })
            .unwrap_or_else(std::env::temp_dir);
        local.join(CLI_ROOT_DIR_NAME).join("bin")
    }
    #[cfg(not(windows))]
    {
        let home = app_handle
            .path()
            .home_dir()
            .unwrap_or_else(|| PathBuf::from("."));
        home.join(UNIX_BIN_DIR)
    }
}

/// 主 shim 文件路径
fn get_shim_path(app_handle: &AppHandle) -> PathBuf {
    #[cfg(windows)]
    {
        get_bin_dir(app_handle).join(SHIM_CMD_NAME)
    }
    #[cfg(not(windows))]
    {
        get_bin_dir(app_handle).join(SHIM_SH_NAME)
    }
}

/// 当前用户 PATH 中是否已包含 bin 目录（Windows 以注册表为准，
/// 因为进程内 PATH 在广播 WM_SETTINGCHANGE 后不会自动更新）
fn path_registered(app_handle: &AppHandle) -> bool {
    #[cfg(windows)]
    {
        let bin_dir = get_bin_dir(app_handle);
        let Some(bin_str) = bin_dir.to_str() else {
            return false;
        };
        read_user_path()
            .map(|value| path_contains_token(&value, bin_str))
            .unwrap_or(false)
    }
    #[cfg(not(windows))]
    {
        let bin_dir = get_bin_dir(app_handle);
        // 1. 当前进程 PATH 已包含（新终端直接可用）
        if std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default())
            .any(|p| p == bin_dir)
        {
            return true;
        }
        // 2. rc 文件中已注入标记块（重启 shell 后可用）
        let home = app_handle
            .path()
            .home_dir()
            .unwrap_or_else(|| PathBuf::from("."));
        RC_FILES.iter().any(|name| {
            fs::read_to_string(home.join(name))
                .map(|content| content.contains(RC_MARK_START))
                .unwrap_or(false)
        })
    }
}

